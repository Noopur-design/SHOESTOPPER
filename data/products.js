// Format a rupee amount with Indian digit grouping, e.g. 12999 -> "₹12,999".
export function formatPrice(amount) {
  return `₹${Number(amount).toLocaleString("en-IN")}`;
}

export function getProduct(id) {
  return products.find((p) => p.id === id);
}

export function getRelated(id, limit = 3) {
  const current = getProduct(id);
  if (!current) return products.slice(0, limit);
  return products
    .filter((p) => p.id !== id && p.category === current.category)
    .concat(products.filter((p) => p.id !== id && p.category !== current.category))
    .slice(0, limit);
}
